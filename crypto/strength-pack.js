// crypto/strength-pack.js - packs the word lists of crypto/strength-words.txt into crypto/strength-data.js:
//   node crypto/strength-pack.js            (importing the module runs nothing)
//
// strength-words.txt: '#' comment lines, '[name]' section lines (passwords, english, names, surnames, russian, in this
// order), words separated by white space, most frequent first. The packer lower-cases, checks the alphabet of each
// list, drops words shorter than 3 characters, keeps the first occurrence inside a list and, across lists, only the
// occurrence with the lowest rank (as zxcvbn's list builder does). Output: "name\nword\n..." sections joined by NUL,
// UTF-8, raw deflate level 9 (codec/zlib.js), Base64 in 120-character lines.
//
// Why packed: the ~22 000 frequency-ranked words are text that compresses well, and a Base64 string in a JS module
// is bundled like any other code (works from file://, no fetch). Decoding costs one inflate on first use
// (strength.js lexicon()). Build-time tool: Node-only imports, never imported by the apps.
// Cross-list dedup keeps a word only in the list where it ranks best, so the runtime Map needs one entry per word.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateRawSync } from '../codec/zlib.js';
import { bytesToBase64 } from './encoding.js';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const isMain = typeof process !== 'undefined' && process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

// Allowed alphabet per list (also fixes the section order of the output). Words outside it are counted as rejected,
// which catches encoding accidents in strength-words.txt (e.g. Latin homoglyphs inside Russian words).
export const LISTS = {
  passwords: /^[\x21-\x7e]+$/,
  english: /^[a-z]+$/,
  names: /^[a-z]+$/,
  surnames: /^[a-z]+$/,
  russian: /^[а-яё]+$/,
};

export function parseLists(text) {
  const lists = {};
  let cur = null;
  for (const line of text.split(/\r?\n/)) {
    if (/^\s*#/.test(line) || !line.trim()) continue;
    const head = /^\[(\w+)\]\s*$/.exec(line);
    if (head) {
      if (!LISTS[head[1]]) throw new Error(`unknown list [${head[1]}]`);
      cur = lists[head[1]] = lists[head[1]] || [];
      continue;
    }
    if (!cur) throw new Error('words before the first [list] line');
    cur.push(...line.trim().split(/\s+/));
  }
  return lists;
}

export function packLists(lists) {
  const report = {};
  const best = new Map(); // word -> [list, rank]
  const clean = {};
  for (const [name, rx] of Object.entries(LISTS)) {
    const seen = new Set(), out = [];
    let bad = 0;
    for (const raw of lists[name] || []) {
      const w = raw.toLowerCase();
      const n = [...w].length;
      if (n < 3 || n > 32 || !rx.test(w)) { bad++; continue; }
      if (seen.has(w)) continue;
      seen.add(w);
      out.push(w);
      const b = best.get(w);
      if (!b || b[1] > out.length) best.set(w, [name, out.length]);
    }
    clean[name] = out;
    report[name] = { read: (lists[name] || []).length, rejected: bad };
  }
  const sections = [], counts = {};
  for (const [name, words] of Object.entries(clean)) {
    const kept = words.filter((w) => best.get(w)[0] === name);
    counts[name] = kept.length;
    report[name].kept = kept.length;
    sections.push([name, ...kept].join('\n'));
  }
  const raw = new TextEncoder().encode(sections.join('\0'));
  const packed = deflateRawSync(raw, { level: 9 });
  return { counts, report, rawSize: raw.length, packedSize: packed.length, base64: bytesToBase64(packed) };
}

// The emitted module text (header included) is fixed here; edit the generated file only through this function.
export function dataModule({ counts, base64 }) {
  const lines = base64.match(/.{1,120}/g) || [];
  return `// crypto/strength-data.js - GENERATED by \`node crypto/strength-pack.js\` from crypto/strength-words.txt: do not edit.
// The frequency-ranked word lists of crypto/strength.js: "name\\nword\\nword..." sections joined by NUL, UTF-8, raw
// deflate (codec/zlib.js), Base64 (white space is ignored).

export const WORD_COUNTS = ${JSON.stringify(counts).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ')};

export const WORD_LISTS = \`
${lines.join('\n')}
\`;
`;
}

if (isMain) {
  const text = fs.readFileSync(path.join(DIR, 'strength-words.txt'), 'utf8');
  const r = packLists(parseLists(text));
  fs.writeFileSync(path.join(DIR, 'strength-data.js'), dataModule(r));
  for (const [name, v] of Object.entries(r.report)) console.log(`${name.padEnd(10)} read ${v.read}, rejected ${v.rejected}, kept ${v.kept}`);
  console.log(`raw ${r.rawSize} bytes -> deflate ${r.packedSize} bytes -> Base64 ${r.base64.length} characters`);
}
