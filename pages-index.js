const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const read = (f) => { try { return fs.readFileSync(f, 'utf8'); } catch { return null; } };

// Inline Markdown of a README cell or a list item: `code`, **bold**, [text](link) -> text.
function inline(md) {
  return esc(md.replace(/\[([^\]]+)\]\([^)]*\)/g, '$1'))
    .replace(/`([^`]+)`/g, '<code>$1</code>').replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>');
}

// Application rows of a README table: | [app](…/app/) | class | description | try it |
function readmeRows(file) {
  const rows = new Map();
  for (const line of (read(file) || '').split(/\r?\n/)) {
    const m = /^\|\s*\[([a-z0-9-]+)\]\([^)]*\)\s*\|([^|]*)\|([^|]*)\|/.exec(line);
    if (m) rows.set(m[1], { cls: m[2].trim(), desc: m[3].trim() });
  }
  return rows;
}

// 'Resume builder: a visual editor …' -> { title: 'Resume builder', summary: 'a visual editor …' } (shortened).
function split(desc, fallback) {
  const i = desc.indexOf(': ');
  let title = fallback, rest = desc;
  if (i > 0 && i < 48) { title = desc.slice(0, i); rest = desc.slice(i + 2); }
  rest = rest.replace(/^./, (c) => c.toUpperCase());
  if (rest.length > 220) rest = rest.slice(0, rest.lastIndexOf(' ', 210)).replace(/[,;:(—–-]+$/, '') + '…';
  return { title, summary: rest };
}

const titleCase = (s) => s.toLowerCase().replace(/(^|[\s-])(\p{L})/gu, (m, a, b) => a + b.toUpperCase());

function noticeTags(appDir) {
  const tags = new Set();
  for (const f of fs.readdirSync(appDir)) {
    const m = /^(?:SINGLEFILE_)?(OFFLINE|SERVERLESS|BACKEND|STANDALONE|ELECTRON)(?:_SINGLEFILE)?_NOTICE\.md$/.exec(f);
    if (m) tags.add(m[1].toLowerCase());
  }
  return [...tags];
}

function collectApps(root, out, langs) {
  const apps = listApps(root);
  const bases = new Map();
  for (const a of apps) bases.set(a.split('-')[0].toUpperCase(), (bases.get(a.split('-')[0].toUpperCase()) || 0) + 1);
  const published = fs.readdirSync(out).filter((f) => /\.html$/.test(f));
  const demos = new Set(fs.existsSync(path.join(out, 'demo')) ? fs.readdirSync(path.join(out, 'demo')) : []);
  const rows = Object.fromEntries(langs.map((l) => [l, readmeRows(l === 'en' ? path.join(root, 'README.md') : path.join(root, '.t9n', l, 'README.md'))]));
  const list = [];
  for (const app of apps) {
    const dir = path.join(root, app);
    const base = bases.get(app.split('-')[0].toUpperCase()) > 1 ? app.toUpperCase() : app.split('-')[0].toUpperCase();
    const pages = published.filter((f) => f === `${base}.html` || f.startsWith(`${base}.`)).sort((a, b) => (a === `${base}.html` ? -1 : b === `${base}.html` ? 1 : a.localeCompare(b)));
    let slug = null;
    try { slug = demoSlug(dir); } catch { /* malformed notice: no demo link */ }
    const demo = slug && demos.has(`${slug}.html`) ? `demo/${slug}.html` : null;
    if (!pages.length && !demo) continue;
    const notice = read(path.join(dir, 'DEMO_NOTICE.md'));
    const named = notice && /^#\s+(.+)$/m.exec(notice);
    const fallback = named ? titleCase(named[1].trim()) : titleCase(app.replace(/-/g, ' '));
    const text = {};
    for (const l of langs) {
      const r = rows[l].get(app) || rows.en.get(app);
      text[l] = r ? { ...split(r.desc, fallback), cls: r.cls } : { title: fallback, summary: '', cls: '' };
    }
    list.push({ app, base, pages, demo, tags: noticeTags(dir), text });
  }
  return list;
}

// Programme of one language: { title, lead, parts: [{ heading, items: [{ slug, title }] }] } from LEARN_COURSE.md,
// or one unnamed part with every course of the language in name order.
function programme(root, lang, out) {
  const courses = listCourses(root).filter((c) => (c.lang || 'en') === lang);
  const prefix = (lang === 'en' ? '' : lang + '/') + SECTION + '/';
  const exists = (slug) => fs.existsSync(path.join(out, prefix + slug + '.html'));
  const titleOf = (c) => (/^#\s+(.+)$/m.exec(read(path.join(c.dir, c.file)) || '') || [])[1] || c.slug;
  const src = read(path.join(courses[0]?.dir || path.join(root, '.t9n', lang), 'LEARN_COURSE.md'));
  const result = { title: null, lead: '', parts: [] };
  const seen = new Set();
  if (src) {
    const lines = src.split(/\r?\n/);
    result.title = (/^#\s+(.+)$/m.exec(src) || [])[1] || null;
    const h1 = lines.findIndex((l) => /^#\s/.test(l));
    const lead = [];
    for (let i = h1 + 1; i < lines.length && !/^#/.test(lines[i]); i++) {
      if (lines[i].trim()) lead.push(lines[i].trim()); else if (lead.length) break;
    }
    result.lead = lead.join(' ');
    let part = null;
    for (const line of lines) {
      const h = /^##\s+(.+)$/.exec(line);
      if (h) { part = { heading: h[1].trim(), items: [] }; result.parts.push(part); continue; }
      const m = /^\s*(?:\d+\.|[-*])\s+\[(.+?)\]\((?:\.\/)?(LEARN_[A-Z0-9_]+_COURSE)\.md\)(.*)$/.exec(line);
      if (!m) continue;
      const slug = m[2].replace(/^LEARN_|_COURSE$/g, '').toLowerCase().replace(/_/g, '-');
      if (!part) { part = { heading: '', items: [] }; result.parts.push(part); }
      part.items.push({ slug, title: m[1], note: m[3].replace(/^\s*[—–-]\s*/, '').trim(), live: exists(slug) });
      seen.add(slug);
    }
  }
  const rest = courses.filter((c) => !seen.has(c.slug) && exists(c.slug)).sort((a, b) => a.slug.localeCompare(b.slug));
  if (rest.length) result.parts.push({ heading: '', items: rest.map((c) => ({ slug: c.slug, title: titleOf(c), note: '', live: true })) });
  result.parts = result.parts.filter((p) => p.items.length);
  result.count = result.parts.reduce((n, p) => n + p.items.filter((i) => i.live).length, 0);
  return result;
}

