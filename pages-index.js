// per language, so the site root is never empty.
//
//   node pages-index.js <dir>        (run after singlefile.js --publish <dir>, --demo <dir>/demo and course.js --out <dir>)
//
// Languages: English at the root, every other language under <lang>/ (one per .t9n/<lang>/ folder):
//   <dir>/index.html                       applications (English descriptions from README.md)
//   <dir>/<lang>/index.html                applications (descriptions from .t9n/<lang>/README.md, English as fallback)
//   <dir>/course/in-html/index.html        course programme (courses of every language, the English ones first)
//   <dir>/<lang>/course/in-html/index.html programme from .t9n/<lang>/LEARN_COURSE.md (parts and order kept)
// Every page links to the same page in the other languages.
//
// Nothing here is maintained by hand: applications come from listApps(), their pages from the published names that
// exist in <dir>, demos from DEMO_NOTICE.md, artifact tags from the NOTICE files, descriptions from the README tables,
// courses from course.js. An application or course that was not published gets no card, so no link is ever dead.
// The pages are static HTML with a small inline script (search and tag filters); without JavaScript every card shows.

