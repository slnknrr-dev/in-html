function coursesPage(lang, langs, progs) {
  const t = tr(lang);
  const depth = (lang === 'en' ? 0 : 1) + SECTION.split('/').length;
  const up = upTo(depth);
  const own = progs[lang];
  let body = '';
  if (own && own.count) {
    let start = 0; // numbering continues across parts
    body = own.parts.map((p) => {
      const ol = `${p.heading ? `<h2 class="part">${inline(p.heading)}</h2>` : ''}<ol class="courses" style="counter-reset:c ${start}">
${p.items.map((i) => `<li>${i.live ? `<a href="${esc(i.slug)}.html"><span class="n"></span><span>${inline(i.title)}${i.note ? `<small>${inline(i.note)}</small>` : ''}</span></a>` : `<span class="soon"><span class="n"></span><span>${inline(i.title)}</span></span>`}</li>`).join('\n')}
</ol>`;
      start += p.items.length;
      return ol;
    }).join('\n');
  } else {
    const other = langs.filter((l) => progs[l] && progs[l].count);
    body = `<p>${esc(t.otherLang)}</p><div class="btns">${other.map((l) => `<a class="btn primary" href="${up}${home(l)}${SECTION}/index.html">${esc(LANG_NAMES[l] || l)} · ${progs[l].count}</a>`).join('')}</div>`;
  }
  const hero = `<h1>${esc(own && own.title ? own.title : t.programme)}</h1><p class="lead">${own && own.lead ? inline(own.lead) : esc(t.programmeLead)}</p>
<div class="stats"><a href="${up}${home(lang)}index.html">${esc(t.toApps)}</a>${own && own.count ? `<span><b>${own.count}</b>${esc(t.coursesShort)}</span>` : ''}</div>`;
  const langLinks = langs.map((l) => ({ lang: l, href: up + home(l) + SECTION + '/index.html' }));
  return shell({ lang, title: `in-html — ${t.courses}`, up, langLinks, hero, body: `<div style="height:8px"></div>${body}` });
}

export function buildIndexes(out, root = ROOT) {
  const t9n = path.join(root, '.t9n');
  const langs = ['en', ...(fs.existsSync(t9n) ? fs.readdirSync(t9n, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort() : [])];
  const apps = collectApps(root, out, langs);
  const progs = Object.fromEntries(langs.map((l) => [l, programme(root, l, out)]));
  const files = new Map();
  for (const lang of langs) {
    const courseCount = progs[lang].count || langs.reduce((n, l) => n + (progs[l].count || 0), 0);
    files.set(home(lang) + 'index.html', appsPage(lang, langs, apps, courseCount));
    files.set(home(lang) + SECTION + '/index.html', coursesPage(lang, langs, progs));
  }
  for (const [rel, html] of files) {
    fs.mkdirSync(path.dirname(path.join(out, rel)), { recursive: true });
    fs.writeFileSync(path.join(out, rel), html);
  }
  return { langs, apps: apps.length, files: [...files.keys()] };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = process.argv[2];
  if (!out) { console.error('usage: node pages-index.js <published dir>'); process.exit(2); }
  const r = buildIndexes(path.resolve(out));
  console.log(`pages-index: ${r.apps} applications, languages ${r.langs.join(', ')} -> ${r.files.join(', ')}`);
}
