// site-studio/backend-server.js - the server of a landing exported as a backend archive (CONTRACT.md §16):
// the static site from public/, the JSON API of the page's 'local:' endpoints, the built-in chat (long-poll), the admin
// console and its API, and regeneration of the static site with the landing engine after content changes.
//
//   startServer({ http, fs, path, crypto, zlib?, Buffer, root, argv, env, log }) -> Promise<{ server, port, close(), rebuild() }>
//
// Node >= 20, Bun or Deno; no dependencies. The Node built-ins are handed in by the archive's launcher (server.mjs), so
// this module imports none and is bundled with the engine into lib/site.mjs (backend-engine.js). Data:
//   <DATA_DIR = root/data>/site.json            the page document (source of public/)
//                          build.json           export settings: target 'backend' | 'hybrid', langs, minify, labels…
//                          .admin-token         generated admin token (when ADMIN_TOKEN is not set)
//                          collections/<c>.json private records { v, collection, records: [{ id, at, data }] } and the chat
//   <root>/public/                              the static site (index.html, <page>/index.html, 404.html, assets/,
//                                               data/<collection>.json; .pages.json lists the generated page files)
// Pages (CONTRACT.md §18): /<slug>/ serves the prerendered page; case, '.html', 'index.html' and missing-slash variants
// of a page address are redirected (301) to it; any other unknown address answers 404 with public/404.html.
//
// Design rules of this module:
// - One process, in-memory state, write-through to JSON files with atomic rename. No database: an archive must run
//   with `node server.mjs` on any host; the price is a single-writer assumption (never run two instances on one DATA).
// - The static site is a build artefact of site.json, regenerated by the same engine the editor exports with, so what
//   the editor previews and what the server serves cannot drift. Admin edits change the document, then rebuild.
// - Trust boundaries: visitors may only write into collections the plan (planBackend) declares writable, with bounded
//   shapes (okValue, LIMIT); everything under api/_admin needs the admin token or an admin session; every write needs
//   a same-origin request (sameOrigin) as CSRF defence, since there is no CORS.
// - Errors carrying `status` are client errors answered with their message; anything else is logged and answered 500
//   without details (no stack traces to visitors).
