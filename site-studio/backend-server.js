  const chatOn = () => !!ruleOf('chat');
  // Visitor names are not echoed back to visitors (only the operator's display name), so no visitor data leaks out.
  const pubMsg = (m) => ({ id: m.id, from: m.from, name: m.from === 'operator' ? m.name || '' : '', text: m.text, at: m.at, seq: m.seq });
  const convOf = (id) => (typeof id === 'string' && MSG_ID_RE.test(id) ? coll('chat').byId.get(id) || null : null);

  // The conversation id (20 random chars) is the visitor's only credential: whoever has it reads the conversation.
  // Message ids from the client make resends idempotent. Only http(s) page URLs are stored (no javascript: links shown
  // in the console).
  async function apiChat(req, res, conv, q) {
    if (!chatOn()) return fail(req, res, 404, 'no chat');
    const c = coll('chat');
    if (!conv && req.method === 'POST') {
      const body = await readJSONBody(req, LIMIT.body);
      if (!isObj(body) || !isObj(body.message)) return fail(req, res, 400, 'invalid body');
      const text = str(body.message.text).replace(/\r\n?/g, '\n').trim().slice(0, LIMIT.text);
      if (!text) return fail(req, res, 400, 'empty message');
      const vis = isObj(body.visitor) ? body.visitor : {};
      const now = Date.now();
      let cv = convOf(body.conv);
      if (!cv) {
        if (c.records.length >= LIMIT.convs) return fail(req, res, 507, 'storage full');
        const id = randomId(20);
        cv = { id, at: now, data: { up: now, seq: 0, unread: 0, visitor: { name: '', contact: '' }, lang: '', page: '', msgs: [] } };
        c.records.push(cv);
        c.byId.set(id, cv);
      }
      const D = cv.data;
      if (D.msgs.length >= LIMIT.msgs) return fail(req, res, 507, 'conversation full');
      const name = str(vis.name).trim().slice(0, 200);
      const contact = str(vis.contact).trim().slice(0, 200);
      if (name) D.visitor.name = name;
      if (contact) D.visitor.contact = contact;
      D.lang = str(body.lang).slice(0, 35) || D.lang;
      D.page = /^https?:\/\//.test(str(body.page)) ? str(body.page).slice(0, 500) : D.page;
      const mid = MSG_ID_RE.test(str(body.message.id)) ? str(body.message.id) : 'v' + randomId(12);
      let msg = D.msgs.find((x) => x.id === mid);
      if (!msg) {
        msg = { id: mid, seq: ++D.seq, from: 'visitor', name: D.visitor.name, text, at: now };
        D.msgs.push(msg);
        D.unread++;
        D.up = now;
        persist(c);
      }
      return json(req, res, 201, { ok: true, conv: cv.id, cursor: D.seq, messages: [pubMsg(msg)] });
    }
    if (conv && (req.method === 'GET' || req.method === 'HEAD')) {
      const cv = convOf(conv);
      if (!cv) return fail(req, res, 404, 'unknown conversation');
      const since = Math.max(0, Math.floor(Number(q.get('since')) || 0));
      const wait = Math.min(25, Math.max(0, Math.floor(Number(q.get('wait')) || 0)));
      const test = () => { const D = cv.data; const news = D.msgs.filter((m) => m.seq > since); return news.length ? news : null; };
      return waitFor(req, wait, test, (news) => json(req, res, 200, { messages: (news || []).map(pubMsg), cursor: news ? cv.data.seq : since }));
    }
    return fail(req, res, 405, 'method not allowed');
  }

