// Block types of the portal used by a published base (every page and version); null: every type.
// Scans every version of every page (not only the first): a portal block may appear only in an alternative version.
export function portalTypesOf(site) {
  if (!site) return null;
  const used = new Set();
  const visit = (list) => {
    for (const b of list || []) {
      if (b && PORTAL_TYPES.includes(b.type)) used.add(b.type);
      if (b && b.type === 'columns') for (const c of b.cols || []) visit(c.blocks);
    }
  };
  for (const p of site.pages || []) for (const v of p.versions || []) visit(v.blocks);
  return [...used];
}

// The stylesheet of a published base: the reader's, plus the portal chunks its pages use (and the search page's type
// tabs when any portal block is used). readerCSS(null) carries every chunk (editor preview).
// Pay-for-what-you-use: a base without portal blocks ships only READER_CSS; otherwise only the used portal chunks
// plus 'finder' (the search page renders portal results in finder tabs whenever any portal block exists).
// Unlocked 451 pages are not scanned (they are sealed at export time), so a portal block that exists only inside a
// secret page renders unstyled for readers who unlock it. Accepted: including its CSS would hint at its content.
export function readerCSS(site) {
  const types = portalTypesOf(site);
  if (types && !types.length) return READER_CSS;
  return READER_CSS + PORTAL_TOKENS + portalCSS('kp', types ? [...new Set([...types, 'finder'])] : null);
}
